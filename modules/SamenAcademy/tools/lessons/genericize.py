def run(path):
    s = open(path, encoding='utf8').read(); o = s
    for a, b in sorted(MAP, key=lambda x: -len(x[0])):
        s = s.replace(a, b)
    if s != o: open(path, 'w', encoding='utf8').write(s)
    return s != o
