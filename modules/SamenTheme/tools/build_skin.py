#!/usr/bin/env python3
"""
Build the Vtiger 8 custom skin  layouts/v7/custom_skins/samen/<app>/style.css  for every app.

For each app skin (contact, sales, ...):
  1. compile Vtiger's own LESS (skins/vtiger/style.less + the app's variables and extra rules) with the
     SamenStudent palette from source_less/samen/variables.less    (needs lessc 4: npm i -g less@4)
  2. append resources/theme.css           – design tokens + component polish
  3. append the mirrored RTL rules         – make_rtl_css.py over Bootstrap/todc + the compiled skin
  4. append resources/rtl.css             – hand-written RTL fixes (menus with inline styles, icons...)
Images/fonts of the stock skins are copied next to it by SamenTheme.php at install time.
"""
import os, re, subprocess, sys, io, contextlib
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import make_rtl_css

LESSC = os.environ.get("LESSC", "lessc")
SRC = os.path.join(HERE, "source_less")
RES = os.path.join(ROOT, "layouts/v7/modules/SamenTheme/resources")
OUT = os.path.join(ROOT, "layouts/v7/custom_skins/samen")
APPS = ["contact", "inventory", "marketing", "marketing_and_sales", "project", "sales", "support", "tools"]
BOOT = [os.path.join(HERE, "source_css", f) for f in
        ("layouts_v7_lib_todc_css_bootstrap.min.css", "layouts_v7_lib_todc_css_todc-bootstrap.min.css")]
FONT_URL = "../../../modules/SamenTheme/resources/fonts/"     # from custom_skins/samen/<app>/style.css


def rtl_for(paths):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(io.StringIO()):
        make_rtl_css.main(paths)
    return buf.getvalue()


def main():
    theme = open(os.path.join(RES, "theme.css"), encoding="utf-8").read().replace("url('fonts/", "url('" + FONT_URL)
    rtl_hand = open(os.path.join(RES, "rtl.css"), encoding="utf-8").read()
    for app in APPS:
        extras = open(os.path.join(SRC, app, "style.less"), encoding="utf-8").read().split("\n")[3:]
        entry = os.path.join(SRC, app, "samen.less")
        with open(entry, "w", encoding="utf-8") as f:
            f.write('@import "../vtiger/variables.less";\n@import "variables.less";\n@import "../samen/variables.less";\n'
                    '@import "../vtiger/style.less";\n' + "\n".join(extras))
        css = subprocess.run([LESSC, entry], check=True, capture_output=True, text=True).stdout
        os.remove(entry)
        tmp = os.path.join(SRC, f"_{app}.css")
        open(tmp, "w", encoding="utf-8").write(css)
        rtl = rtl_for(BOOT + [tmp])
        os.remove(tmp)
        os.makedirs(os.path.join(OUT, app), exist_ok=True)
        out = os.path.join(OUT, app, "style.css")
        with open(out, "w", encoding="utf-8") as f:
            f.write(f"/* SamenStudent custom skin for Vtiger ({app}). GENERATED by modules/SamenTheme/tools/build_skin.py – do not edit. */\n")
            f.write(css)
            f.write("\n/* ===== theme.css ===== */\n" + theme)
            f.write("\n/* ===== RTL (generated) ===== */\n" + rtl)
            f.write("\n/* ===== rtl.css ===== */\n" + rtl_hand)
        print(f"{app:20s} {os.path.getsize(out)//1024} KB")


if __name__ == "__main__":
    main()
