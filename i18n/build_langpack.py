#!/usr/bin/env python3
"""
Build the Persian (fa_ir) Vtiger language pack as a standard vtlib package.

  python3 build_langpack.py            -> dist/Persian_fa_ir.zip  (+ dist/Persian_fa_ir/ unpacked)

Inputs
  source/en_us.json     dump of languages/en_us (tools/dump_lang.php, run in the web container)
  source/strings.json   unique English strings with ids (tools/extract_strings.py)
  fa/*.txt              translations, one "id<TAB>persian" per line
  custom/fa_custom.json extra keys per file (SamenStudent fields, picklist values, ...), merged last

Every file of en_us is reproduced with the same keys; a missing translation falls back to English
(and is reported). Placeholders (%s, %d, {0}, $var$) and HTML tags must survive translation.
Install: Settings > Module Manager > Import Module from Zip, or scripts/install_persian.sh.
"""
import collections
import glob
import json
import os
import re
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
PREFIX, NAME, LABEL, VERSION = "fa_ir", "Persian", "فارسی", "1.0.0"
DIST = os.path.join(HERE, "dist")

PH_RE = re.compile(r"%[sd]|\{\d+\}|\$[a-z_-]+\$")
TAG_RE = re.compile(r"</?\s*([a-zA-Z]+)[^>]*>|&lt;/?([a-zA-Z]+)")


def load_translations():
    tr = {}
    for f in sorted(glob.glob(os.path.join(HERE, "fa", "*.txt"))):
        for n, line in enumerate(open(f, encoding="utf-8"), 1):
            line = line.rstrip("\n")
            if not line.strip():
                continue
            i, _, fa = line.partition("\t")
            tr[int(i)] = fa
    return tr


def check(en, fa):
    probs = []
    if collections.Counter(PH_RE.findall(en)) != collections.Counter(PH_RE.findall(fa)):
        probs.append("placeholders")
    tags = lambda s: collections.Counter(a.lower() or b.lower() for a, b in TAG_RE.findall(s))
    if tags(en) != tags(fa):
        probs.append("html tags")
    return probs


def php_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def php_array(name, kv):
    if not kv:
        return f"${name} = array();\n"
    rows = [f"\t{php_str(str(k))} => {php_str(v)}," for k, v in kv.items()]
    return f"${name} = array(\n" + "\n".join(rows) + "\n);\n"


def main():
    en = json.load(open(os.path.join(HERE, "source", "en_us.json"), encoding="utf-8"))
    strings = json.load(open(os.path.join(HERE, "source", "strings.json"), encoding="utf-8"))
    custom_path = os.path.join(HERE, "custom", "fa_custom.json")
    custom = json.load(open(custom_path, encoding="utf-8")) if os.path.exists(custom_path) else {}
    tr = load_translations()
    by_en = {}
    missing, bad = [], []
    for e in strings:
        fa = tr.get(e["id"])
        if fa is None or not fa.strip():
            missing.append(e)
            continue
        p = check(e["en"], fa)
        if p:
            bad.append((e["id"], p, e["en"][:80], fa[:80]))
            continue          # keep English rather than ship a broken string
        by_en[e["en"]] = fa

    out_root = os.path.join(DIST, f"{NAME}_{PREFIX}")
    files = {}
    for rel, vars_ in en.items():
        body = "<?php\n/*+***********************************************************************************\n" \
               " * Persian (fa_ir) language pack for Vtiger CRM - SamenStudent\n" \
               " * Generated by codes/i18n/build_langpack.py from languages/en_us. Do not edit by hand.\n" \
               " ************************************************************************************/\n"
        for var in ("languageStrings", "jsLanguageStrings", "mod_strings"):
            if var not in vars_ and not (var in ("languageStrings", "jsLanguageStrings") and custom.get(rel, {}).get(var)):
                continue
            src = vars_.get(var) or {}
            kv = {}
            if isinstance(src, dict):
                for k, v in src.items():
                    kv[k] = by_en.get(v, v) if isinstance(v, str) else v
            kv.update(custom.get(rel, {}).get(var, {}))
            kv = {k: v for k, v in kv.items() if isinstance(v, str)}
            body += php_array(var, kv)
        files[rel] = body
    # custom files that do not exist in en_us (none expected, but allowed)
    for rel, vars_ in custom.items():
        if rel not in files:
            body = "<?php\n"
            for var, kv in vars_.items():
                body += php_array(var, kv)
            files[rel] = body

    manifest = f"""<?xml version="1.0"?>
<module>
	<type>language</type>
	<name>{NAME}</name>
	<label>{LABEL}</label>
	<prefix>{PREFIX}</prefix>
	<version>{VERSION}</version>
	<dependencies>
		<vtiger_version>7.0.0</vtiger_version>
		<vtiger_max_version>8.*</vtiger_max_version>
	</dependencies>
	<license>
		<inline><![CDATA[Persian translation for SamenStudent. Same license as Vtiger CRM (VPL 1.1).]]></inline>
	</license>
</module>
"""
    os.makedirs(DIST, exist_ok=True)
    zpath = os.path.join(DIST, f"{NAME}_{PREFIX}.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("manifest.xml", manifest)
        for rel, body in sorted(files.items()):
            z.writestr("modules/" + rel, body)
            p = os.path.join(out_root, "modules", rel)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w", encoding="utf-8").write(body)
    open(os.path.join(out_root, "manifest.xml"), "w", encoding="utf-8").write(manifest)

    print(f"translated {len(by_en)}/{len(strings)} unique strings; missing {len(missing)}; rejected {len(bad)}")
    for m in missing[:20]:
        print("  MISSING", m["id"], m["en"][:70])
    for b in bad[:40]:
        print("  REJECTED", *b)
    print(f"{len(files)} files -> {zpath}")
    return 1 if (missing or bad) and "--strict" in sys.argv else 0


if __name__ == "__main__":
    sys.exit(main())
